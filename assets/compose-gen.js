/* n8n Docker Compose + .env generator. Pure functions (unit-tested); secrets are generated in the browser. */
(function (root) {
  function randomHex(bytes) {
    const a = new Uint8Array(bytes);
    (root.crypto || require('crypto').webcrypto).getRandomValues(a);
    return Array.from(a, b => b.toString(16).padStart(2, '0')).join('');
  }
  function validate(o) {
    const errs = [];
    if (!/^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i.test(o.domain || '') && o.domain !== 'localhost') errs.push('Domain should look like n8n.example.com');
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(o.email || '')) errs.push('Enter a valid email for Let\'s Encrypt notices');
    if (!/^[A-Za-z_]+(\/[A-Za-z0-9_+\-]+){1,2}$/.test(o.timezone || '') && o.timezone !== 'UTC') errs.push('Timezone should be an IANA name like America/New_York');
    if (!/^\d+\.\d+\.\d+$/.test(o.version || '')) errs.push('Pin an exact n8n version like 2.40.6');
    return errs;
  }
  function generate(o, rnd) {
    rnd = rnd || randomHex;
    const pg = rnd(24), key = rnd(32);
    const env = [
      '# Generated by the n8n Docker Compose generator. Keep this file private (chmod 600 .env).',
      'DOMAIN=' + o.domain,
      'ACME_EMAIL=' + o.email,
      'GENERIC_TIMEZONE=' + o.timezone,
      'N8N_VERSION=' + o.version,
      'POSTGRES_USER=n8n',
      'POSTGRES_DB=n8n',
      'POSTGRES_PASSWORD=' + pg,
      '# SAVE THIS KEY IN YOUR PASSWORD MANAGER. Without it, backups cannot decrypt your credentials.',
      'N8N_ENCRYPTION_KEY=' + key,
      'EXECUTIONS_DATA_MAX_AGE=' + (o.pruneHours || 336),
      'NODE_FUNCTION_ALLOW_BUILTIN=' + (o.allowTls ? 'tls' : ''),
      '',
    ].join('\n');
    const compose = `# n8n + PostgreSQL 17 + Caddy (automatic HTTPS). Start with: docker compose up -d
services:
  postgres:
    image: postgres:17-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: \${POSTGRES_USER}
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
      POSTGRES_DB: \${POSTGRES_DB}
    volumes:
      - db_data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h localhost -U $\${POSTGRES_USER} -d $\${POSTGRES_DB}"]
      interval: 5s
      timeout: 5s
      retries: 20

  n8n:
    image: docker.n8n.io/n8nio/n8n:\${N8N_VERSION}
    restart: unless-stopped
    depends_on:
      postgres:
        condition: service_healthy
    environment:
      DB_TYPE: postgresdb
      DB_POSTGRESDB_HOST: postgres
      DB_POSTGRESDB_PORT: "5432"
      DB_POSTGRESDB_DATABASE: \${POSTGRES_DB}
      DB_POSTGRESDB_USER: \${POSTGRES_USER}
      DB_POSTGRESDB_PASSWORD: \${POSTGRES_PASSWORD}
      N8N_ENCRYPTION_KEY: \${N8N_ENCRYPTION_KEY}
      N8N_HOST: \${DOMAIN}
      N8N_PROTOCOL: https
      N8N_PORT: "5678"
      WEBHOOK_URL: https://\${DOMAIN}/
      N8N_PROXY_HOPS: "1"
      GENERIC_TIMEZONE: \${GENERIC_TIMEZONE}
      TZ: \${GENERIC_TIMEZONE}
      N8N_ENFORCE_SETTINGS_FILE_PERMISSIONS: "true"
      N8N_RESTRICT_FILE_ACCESS_TO: /files
      EXECUTIONS_DATA_PRUNE: "true"
      EXECUTIONS_DATA_MAX_AGE: \${EXECUTIONS_DATA_MAX_AGE}
      NODE_FUNCTION_ALLOW_BUILTIN: \${NODE_FUNCTION_ALLOW_BUILTIN}
    volumes:
      - n8n_data:/home/node/.n8n
      - ./local-files:/files
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://127.0.0.1:5678/healthz >/dev/null 2>&1 || exit 1"]
      interval: 15s
      timeout: 5s
      retries: 12
      start_period: 40s

  caddy:
    image: caddy:2-alpine
    restart: unless-stopped
    depends_on:
      - n8n
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    environment:
      DOMAIN: \${DOMAIN}
      ACME_EMAIL: \${ACME_EMAIL}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy_data:/data
      - caddy_config:/config

volumes:
  db_data:
  n8n_data:
  caddy_data:
  caddy_config:
`;
    const caddy = `{
	email {$ACME_EMAIL}
}

{$DOMAIN} {
	encode zstd gzip
	reverse_proxy n8n:5678 {
		flush_interval -1
	}
}
`;
    return { env, compose, caddyfile: caddy, keyFingerprintHint: key.slice(0, 4) + '…' + key.slice(-4) };
  }
  const api = { randomHex, validate, generate };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.ComposeGen = api;
})(typeof window !== 'undefined' ? window : globalThis);
